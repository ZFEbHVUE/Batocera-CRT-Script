#!/usr/bin/env bash
# Read-only check of the installed files. The install is not done until this passes.
# REVIEW CANDIDATE ONLY: Not validated on live Batocera. No native saver edits.
# Set VERIFY_TEST_ROOT only in disposable offline fixtures with VERIFY_OFFLINE_TEST=1.
# Initialize counters immediately: boot-custom/save failures can precede verify_all.
VERIFY_LINES=() VERIFY_CHECKS=0 VERIFY_FAILS=0

verify_path() {
  if [[ -n "${VERIFY_TEST_ROOT:-}" && "${VERIFY_OFFLINE_TEST:-}" != 1 ]]; then
    return 2
  fi
  printf '%s%s' "${VERIFY_TEST_ROOT:-}" "$1"
}
verify_check() {
  local name="$1" outcome="$2" detail="${3:-}"
  VERIFY_CHECKS=$((VERIFY_CHECKS + 1))
  if [[ "$outcome" == FAIL ]]; then VERIFY_FAILS=$((VERIFY_FAILS + 1)); fi
  VERIFY_LINES+=("$outcome | $name | $detail")
}
verify_file() {
  local label="$1" path="$2" executable="${3:-no}" f
  f="$(verify_path "$path")" || { verify_check "$label" FAIL 'fixture path refused'; return 1; }
  if [[ ! -f "$f" || -L "$f" || ! -s "$f" ]]; then
    verify_check "$label" FAIL 'missing, symlink, or empty'
  elif [[ "$executable" == yes && ! -x "$f" ]]; then
    verify_check "$label" FAIL 'not executable'
  else verify_check "$label" PASS 'exists with expected type'; fi
}
verify_copy() {
  local label="$1" from="$2" to="$3" executable="${4:-no}" src dst
  src="$(verify_path "${CRTD:?CRTD missing}/$from")" || return 2
  dst="$(verify_path "$to")" || return 2
  if [[ ! -f "$src" || -L "$src" || ! -s "$src" ]]; then
    verify_check "$label" FAIL 'source missing, unsafe, or empty'
  elif [[ ! -f "$dst" || -L "$dst" || ! -s "$dst" ]]; then
    verify_check "$label" FAIL 'destination missing, unsafe, or empty'
  elif ! cmp -s -- "$src" "$dst"; then
    verify_check "$label" FAIL 'destination differs from selected source'
  elif [[ "$executable" == yes && ! -x "$dst" ]]; then
    verify_check "$label" FAIL 'destination not executable'
  else verify_check "$label" PASS 'source and installed bytes match'; fi
}
verify_render() {
  # Compare a generated file with exactly what the original template substitutions produce.
  local label="$1" source="$2" dest="$3" s d
  shift 3
  s="$(verify_path "${CRTD:?CRTD missing}/$source")" || return 2
  d="$(verify_path "$dest")" || return 2
  if [[ ! -s "$s" || -L "$s" || ! -s "$d" || -L "$d" ]]; then
    verify_check "$label" FAIL 'missing/unsafe generated file or template'
  elif ( set -o pipefail; sed "$@" "$s" | cmp -s -- - "$d" ); then
    verify_check "$label" PASS 'generated bytes match selected settings'
  else verify_check "$label" FAIL 'generated bytes do not match template'; fi
}
verify_unique_line() {
  # An exact active key=value; reject a second conflicting/identical active key.
  local label="$1" file="$2" expected="$3" path key
  path="$(verify_path "$file")" || return 2
  key="${expected%%=*}"
  if [[ ! -f "$path" || -L "$path" ]] || ! awk -v k="$key" -v wanted="$expected" '
    /^[[:space:]]*#/ {next}
    { line=$0; sub(/^[[:space:]]*/, "", line)
      pos=index(line,"="); if (!pos) next
      actual=substr(line,1,pos-1); sub(/[[:space:]]*$/, "", actual)
      if (actual==k) {n++; if (line!=wanted) bad=1} }
    END {exit (n==1 && !bad) ? 0 : 1}
  ' "$path"; then
    verify_check "$label" FAIL 'required key missing, changed or duplicated'
  else verify_check "$label" PASS 'exactly one effective key'; fi
}
verify_edid() {
  local f size hdr
  f="$(verify_path "/lib/firmware/edid/${Name_monitor_EDID:-}")" || return 2
  if [[ ! "${Name_monitor_EDID:-}" =~ ^[A-Za-z0-9_-]+\.bin$ || ! -f "$f" || -L "$f" ]]; then
    verify_check 'selected EDID' FAIL 'invalid EDID name or missing file'; return
  fi
  size="$(wc -c < "$f")" || size=0
  hdr="$(od -An -tx1 -N8 "$f" | tr -d '[:space:]')"
  if (( size < 128 || size > 4096 || size % 128 != 0 )) || [[ "$hdr" != 00ffffffffffff00 ]]; then
    verify_check 'selected EDID' FAIL 'invalid EDID header or size'; return
  fi
  if od -An -tu1 -v "$f" | awk -v blocks="$((size / 128))" '
    {for(i=1;i<=NF;i++){n++; sum+=$i; if(n==127) ext=$i;
      if(n%128==0){if(sum%256!=0)bad=1;sum=0}}}
    END {exit !(n==blocks*128 && ext==blocks-1 && !bad)}'; then
    verify_check 'selected EDID' PASS 'all blocks/checksums valid'
  else verify_check 'selected EDID' FAIL 'invalid extension count or checksum'; fi
}
verify_bootres() {
  local f expected_monitor="${CRT_BOOTRES_MONITOR_TYPE:-${monitor_firmware:-}}" count
  f="$(verify_path /userdata/system/logs/BootRes.log)" || return 2
  count="$(wc -l < "$f" 2>/dev/null)" || count=0
  if [[ "$count" == 2 && -n "$expected_monitor" && -n "${EDID_resolution:-}" ]] &&
      grep -Fqx -- "Monitor Type: $expected_monitor" "$f" &&
      grep -Fqx -- "Boot Resolution: $EDID_resolution" "$f"; then
    verify_check 'BootRes selection' PASS 'matches confirmed selection'
  else verify_check 'BootRes selection' FAIL 'not the two expected selected values'; fi
}
verify_switchres() {
  local f monitor="${monitor_firmware:-}"
  f="$(verify_path /etc/switchres.ini)" || return 2
  if [[ ! -s "$f" || -L "$f" || -z "$monitor" ]]; then
    verify_check 'Switchres monitor' FAIL 'no selected monitor or config'; return
  fi
  if awk -v wanted="$monitor" '
   /^[[:space:]]*(#|;|$)/ {next}
   $1=="monitor" {n++; if($2!=wanted) bad=1}
   END {exit (n==1 && !bad) ? 0 : 1}' "$f"; then
    verify_check 'Switchres monitor' PASS 'matches confirmed monitor'
  else verify_check 'Switchres monitor' FAIL 'mismatched or duplicate monitor'; fi
  local key expected
  for key in super_width dotclock_min interlace_force_even; do
    case "$key" in super_width) expected="${super_width:-}";; dotclock_min) expected="${dotclock_min:-}";; interlace_force_even) expected="${IFE:-}";; esac
    if [[ -n "$expected" ]] && awk -v k="$key" -v wanted="$expected" '
       /^[[:space:]]*(#|;|$)/ {next}
       $1==k {n++; if($2!=wanted)bad=1}
       END {exit (n==1&&!bad)?0:1}' "$f"; then
      verify_check "Switchres $key" PASS 'matches confirmed setting'
    else verify_check "Switchres $key" FAIL 'mismatched or duplicate selected setting'; fi
  done
}
verify_xorg() {
  local f selected="${video_output_xrandr:-}"
  f="$(verify_path /etc/X11/xorg.conf.d/10-monitor.conf)" || return 2
  if [[ -z "$selected" || "$selected" == *[!a-zA-Z0-9._:+-]* || ! -s "$f" || -L "$f" ]]; then
    verify_check 'Xorg selected output' FAIL 'missing or unsafe selection/config'; return
  fi
  if awk -v chosen="$selected" '
    /^[[:space:]]*Section "Monitor"/ {section=1;id="";ignore=0;next}
    section && /^[[:space:]]*Identifier "/ {id=$0; sub(/^[[:space:]]*Identifier "/,"",id);sub(/".*/,"",id)}
    section && /Option "Ignore" "true"/ {ignore=1}
    section && /^[[:space:]]*EndSection/ {if(id==chosen){seen++;if(ignore)bad=1};section=0}
    END {exit (seen==1&&!bad)?0:1}' "$f"; then
    verify_check 'Xorg selected output' PASS 'selected connector active once'
  else verify_check 'Xorg selected output' FAIL 'missing/duplicate/ignored output'; fi
}
verify_syslinux() {
  local dual="${IS_DUALBOOT_INSTALL:-false}" f primary expected found=0 path src
  if [[ "$dual" == true ]]; then
    expected="${CRT_APPEND_LINE:-}"
    [[ -n "$expected" ]] || { verify_check 'dual-boot APPEND' FAIL 'missing reviewed APPEND'; return; }
    for f in /boot/EFI/batocera/syslinux.cfg /boot/boot/syslinux.cfg /boot/boot/syslinux/syslinux.cfg; do
      path="$(verify_path "$f")" || return 2
      [[ -e "$path" ]] || continue
      found=$((found+1))
      if [[ ! -f "$path" || -L "$path" ]] || ! awk -v expected="$expected" '
       /^LABEL[[:space:]]+crt[[:space:]]*$/ {labels++; inside=1;next}
       /^LABEL[[:space:]]+/ {inside=0;next}
       inside && /^[[:space:]]*APPEND[[:space:]]+/ {
         n++; text=$0;sub(/^[[:space:]]*APPEND[[:space:]]+/,"",text);if(text!=expected)bad=1}
       END {exit (labels==1&&n==1&&!bad)?0:1}' "$path"; then
        verify_check 'dual-boot CRT APPEND' FAIL 'CRT entry missing/incorrect in existing config'
      else verify_check 'dual-boot CRT APPEND' PASS 'verified existing config'; fi
    done
    if (( found == 0 )); then verify_check 'dual-boot CRT APPEND' FAIL 'no supported configuration exists'; fi
  else
    primary="$(verify_path /boot/boot/syslinux.cfg)" || return 2
    src="$(verify_path "${CRTD:?}/Boot_configs/syslinux.cfg-generic-Batocera")" || return 2
    if [[ ! -s "$src" || ! -s "$primary" || -L "$primary" ]]; then
      verify_check 'single-boot Syslinux' FAIL 'missing template or installed config'; return
    fi
    local -a substitutions=(
       -e "s/\[amdgpu_drivers\]/${drivers_amd:-}/g"
       -e "s/\[card_output\]/${video_output:-}/g"
       -e "s/\[monitor\]/${monitor_firmware:-}.bin/g"
       -e "s|\[card_display\]|${video_output:-}|g"
       -e "s/\[usb_polling\]/${polling_rate:-}/g"
       -e "s/\[boot_resolution\]/${boot_resolution:-}/g"
    )
    local f
    for f in /boot/boot/syslinux.cfg /boot/EFI/syslinux.cfg /boot/EFI/BOOT/syslinux.cfg /boot/EFI/batocera/syslinux.cfg /boot/boot/syslinux/syslinux.cfg; do
      path="$(verify_path "$f")" || return 2
      [[ "$f" == /boot/boot/syslinux.cfg || -d "$(dirname "$path")" ]] || continue
      if [[ ! -s "$path" || -L "$path" ]] || ! (set -o pipefail; sed "${substitutions[@]}" "$src" | cmp -s -- - "$path"); then
        verify_check 'single-boot Syslinux' FAIL 'missing or selected template mismatch'
      else verify_check 'single-boot Syslinux' PASS 'selected template matches boot config'; fi
    done
  fi
}
verify_bootconf() {
  local f drv expected splash
  f="$(verify_path /boot/batocera-boot.conf)" || return 2
  if [[ ! -s "$f" || -L "$f" ]]; then
    verify_check 'boot configuration' FAIL 'missing or unsafe'; return
  fi
  case "${Drivers_Nvidia_CHOICE:-}" in
    Nvidia_Drivers)
      drv="${Drivers_Name_Nvidia_CHOICE:-}"
      case "$drv" in true|legacy470|legacy580) verify_boot_key "$f" nvidia-driver "nvidia-driver=$drv";;
         *) verify_check 'NVIDIA boot setting' FAIL 'unsupported selected driver';; esac ;;
    NOUVEAU) verify_boot_key "$f" nvidia-driver 'nvidia-driver=false' ;;
    *) verify_boot_key "$f" nvidia-driver '#nvidia-driver=true' ;;
  esac
  case "${TYPE_OF_CARD:-}" in NVIDIA) splash='splash.screen.enabled=0';; *) splash='#splash.screen.enabled=0';; esac
  verify_boot_key "$f" splash.screen.enabled "$splash"
  # v44 selection uses kernel parameters for Sea Islands, not an obligatory amdgpu= key.
  if [[ "${BOOT_RESOLUTION:-0}" == 1 ]]; then
    verify_boot_key "$f" es.resolution "es.resolution=${_crt_boot_mode:-}"
  else
    verify_boot_key "$f" es.resolution '#es.resolution=640x480'
  fi
  # Batocera v44 uses kernel parameters for Sea Islands. An optional legacy
  # amdgpu= line, when present, must not contradict the selected installer path.
  if grep -Eq '^[[:space:]#]*amdgpu[[:space:]]*=' "$f"; then
    local amd='#amdgpu=true'
    if [[ "${TYPE_OF_CARD:-}" == 'AMD/ATI' ]]; then
      if [[ "${drivers_type:-}" == AMDGPU ]]; then amd='amdgpu=true'
      else amd='amdgpu=false'; fi
    fi
    verify_boot_key "$f" amdgpu "$amd"
  fi
}
verify_boot_key() {
  local f="$1" key="$2" exact="$3"
  if awk -v k="$key" -v wanted="$exact" '
    {raw=$0;line=$0;sub(/^[[:space:]]*/,"",line)
     if(substr(line,1,2)=="##")next
     if(substr(line,1,1)=="#"){line=substr(line,2);sub(/^[[:space:]]*/,"",line)}
     npos=index(line,"=");if(!npos)next
     name=substr(line,1,npos-1);sub(/[[:space:]]*$/, "",name)
     if(name==k){n++;if(raw!=wanted)bad=1}}
    END {exit (n==1&&!bad)?0:1}' "$f"; then
      verify_check "Boot config $key" PASS 'single expected value'
  else verify_check "Boot config $key" FAIL 'missing, duplicate or wrong value'; fi
}
