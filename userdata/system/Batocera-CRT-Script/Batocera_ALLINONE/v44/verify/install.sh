verify_generated() {
  local root="${CRT_ROMS:-}" key
  if [[ "${Drivers_Nvidia_CHOICE:-}" == Nvidia_Drivers ]]; then
    local template=''
    case "${CRT_Freq:-}" in
      15KHz) template=System_configs/Nvidia/99-nvidia.conf-generic_15 ;;
      25KHz) template=System_configs/Nvidia/99-nvidia.conf-generic_25 ;;
      31KHz) template=System_configs/Nvidia/99-nvidia.conf-generic_31 ;;
      *) verify_check 'NVIDIA CRT monitor configuration' FAIL 'unrecognized selected CRT frequency';;
    esac
    if [[ -n "$template" ]]; then
      if [[ "${CRT_Freq:-}" == 31KHz ]]; then
        verify_render 'NVIDIA CRT monitor configuration' "$template" /userdata/system/99-nvidia.conf \
           -e "s/\[card_display\]/${video_modeline:-}/g"
      else
        verify_render 'NVIDIA CRT monitor configuration' "$template" /userdata/system/99-nvidia.conf \
           -e "s/.*Modeline.*/    Modeline            ${MODELINE_CUSTOM:-}/" \
           -e "s/\[card_display\]/${video_modeline:-}/g"
      fi
    fi
  elif [[ -e "$(verify_path /userdata/system/99-nvidia.conf)" ]]; then
    verify_check 'Non-proprietary NVIDIA monitor cleanup' FAIL 'stale NVIDIA monitor file'
  else
    verify_check 'Non-proprietary NVIDIA monitor cleanup' PASS 'no active proprietary NVIDIA file'
  fi
  for key in /userdata/system/scripts/first_script.sh /userdata/system/scripts/1_GunCon2.sh \
             "$root/crt/GunCon2_Calibration.sh" /usr/bin/guncon2_calibrate.sh /usr/bin/calibrate.py; do
    verify_file "generated executable ${key##*/}" "$key" yes
  done
