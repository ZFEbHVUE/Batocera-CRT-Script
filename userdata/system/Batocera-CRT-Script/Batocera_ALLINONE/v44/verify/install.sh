    'global.retroarch.video_shader_preset_save_reference_enable=true' \
    'global.retroarch.video_shader_enable=true' \
    'global.bezel=none' 'global.hud=none' \
    'mame.core=mame' 'mame.emulator=mame' 'mame.switchres=1' \
    'neogeo.core=mame' 'neogeo.emulator=mame' 'neogeo.switchres=1' \
    'fbneo.video_allow_rotate=off'; do
      verify_unique_line "Required CRT config ${item%%=*}" "$file" "$item"
  done
  local super="0" choice="${es_rotation_choice:-}" rotate=""
  [[ "${dotclock_min:-}" != 25.0 ]] || super="${super_width:-}"
  verify_unique_line 'Switchres super width' "$file" "global.retroarch.crt_switch_resolution_super=$super"
  if [[ "$choice" =~ ^[1-4]$ ]]; then
    verify_unique_line 'ES interface rotation' "$file" "display.rotate=$((choice-1))"
    local -a tate=(none autoror none autorol)
    rotate="${tate[choice-1]}"
    verify_unique_line 'MAME rotation' "$file" "mame.rotation=$rotate"
  else
    verify_check 'ES interface rotation' FAIL 'missing or invalid selected rotation'
  fi
  verify_unique_line 'Selected CRT output' "$file" "global.videooutput=${video_output_xrandr:-}"
  if [[ -n "${_crt_boot_mode:-}" ]]; then
    verify_unique_line 'Selected ES resolution' "$file" "es.resolution=$_crt_boot_mode"
    f="$(verify_path /userdata/system/videomodes.conf)" || return 2
    if [[ -f "$f" && ! -L "$f" ]] && awk -F: -v k="$_crt_boot_mode" '$1==k{found++}END{exit(found==1)?0:1}' "$f"; then
      verify_check 'Selected video mode catalog' PASS 'selected key exists once'
    else verify_check 'Selected video mode catalog' FAIL 'selected key absent/ambiguous'; fi
  else verify_check 'Selected ES resolution' FAIL 'selected mode not resolved'; fi
  verify_file 'CRT videomodes catalog' /userdata/system/videomodes.conf
  verify_file 'CRT geometry saved' /userdata/system/es.arg.override
  verify_file 'MAME selected config backup' /userdata/system/configs/mame/mame.ini.bak
}
verify_all() {
  VERIFY_LINES=() VERIFY_CHECKS=0 VERIFY_FAILS=0
  # Refuse a test-root override unless the offline fixture switch is explicit.
  # Never report success when path resolution has been disabled.
  if [[ -n "${VERIFY_TEST_ROOT:-}" && "${VERIFY_OFFLINE_TEST:-}" != 1 ]]; then
    verify_check 'Verifier environment' FAIL 'unapproved test-root override'
    return 1
  fi
  if [[ "${Version_of_batocera:-}" != v44 ]]; then
    verify_check 'Batocera version' FAIL 'expected v44'
  else verify_check 'Batocera version' PASS 'v44 confirmed'; fi
  verify_bootres
  verify_edid
  verify_switchres
  verify_xorg
  verify_settings
  verify_bootconf
  verify_syslinux
  verify_static
  verify_generated
  (( VERIFY_FAILS == 0 ))
}
verify_overlay_check() {
  local file
  if [[ -n "${VERIFY_TEST_ROOT:-}" && "${VERIFY_OFFLINE_TEST:-}" != 1 ]]; then
    verify_check 'Overlay verifier environment' FAIL 'unapproved test-root override'
    return 1
  fi
  if [[ "${IS_PHASE2:-false}" == true ]]; then file=/boot/crt/overlay;
  else file=/boot/boot/overlay; fi
  verify_file 'Overlay file after save' "$file"
  (( VERIFY_FAILS == 0 ))
}
verify_render_summary() {
  local stage="$1" save="$2" outcome=PASS
  (( VERIFY_FAILS == 0 )) || outcome=FAIL
  printf 'BATOCERA CRT SCRIPT v44 - PHASE 65 INSTALL VERIFICATION\n'
  printf 'Stage: %s\nOutcome: %s\nChecks: %s\nFailures: %s\nSave command: %s\n' \
     "$stage" "$outcome" "$VERIFY_CHECKS" "$VERIFY_FAILS" "$save"
  printf 'Persistence after reboot: NOT TESTED\n'
  printf '%s\n' "${VERIFY_LINES[@]}"
}
verify_write_report() {
  local stage="$1" save="$2" dir out tmp legacy latest_tmp
  case "$stage" in PRE_SAVE|POST_SAVE|SAVE|FINAL) ;; *) return 2 ;; esac
  # Primary durable reports are per-attempt AND per-stage. The original filename
  # stays as the latest-view compatibility copy only; it may be overwritten.
  if [[ -z "${VERIFY_REPORT_RUN_ID:-}" ]]; then
    if [[ "${LOG_RUN_ID:-}" =~ ^CRT_Install_[A-Za-z0-9_-]{1,54}$ ]]; then
      VERIFY_REPORT_RUN_ID="${LOG_RUN_ID}"
    else
      VERIFY_REPORT_RUN_ID="CRT_Install_$(date -u '+%Y%m%dT%H%M%SZ')_${BASHPID}_${RANDOM}"
    fi
  fi
  [[ "$VERIFY_REPORT_RUN_ID" =~ ^CRT_Install_[A-Za-z0-9_-]{1,80}$ ]] || return 2
  out="$(verify_path "/userdata/system/logs/CRT_Installation_Verification_${VERIFY_REPORT_RUN_ID}_${stage}.log")" || return 1
  legacy="$(verify_path /userdata/system/logs/CRT_Installation_Verification.log)" || return 1
  dir="$(dirname "$out")"
  [[ -d "$dir" && ! -L "$dir" ]] || return 1
  tmp="$(umask 077; mktemp "$dir/.verify-report.XXXXXXXX")" || return 1
  if ! verify_render_summary "$stage" "$save" > "$tmp" || ! chmod 600 "$tmp" || ! mv -f -- "$tmp" "$out"; then
    rm -f -- "$tmp"; return 1
  fi
  VERIFY_LAST_REPORT_STAGE="$stage"
  latest_tmp="$(umask 077; mktemp "$dir/.verify-latest.XXXXXXXX")" || return 1
  if ! cat -- "$out" > "$latest_tmp" || ! chmod 600 "$latest_tmp" || ! mv -f -- "$latest_tmp" "$legacy"; then
    rm -f -- "$latest_tmp"; return 1
  fi
  if declare -F log_event >/dev/null 2>&1; then
    log_event INFO 24_finish verification_report_preserved stage "$stage" outcome ok || :
  fi
  return 0
}
verify_emit_summary() {
  local stage="$1" save="$2"
  printf 'CRT installation verification: %s, checks=%s, failed=%s, save=%s\n' \
       "$stage" "$VERIFY_CHECKS" "$VERIFY_FAILS" "$save"
  if declare -F log_event >/dev/null 2>&1; then
    local state=passed
    (( VERIFY_FAILS == 0 )) || state=failed
    local level=INFO
    [[ "$state" == failed ]] && level=ERROR
    log_event "$level" 24_finish verification_summary stage "$stage" outcome "$state" count "$VERIFY_CHECKS" || :
  fi
}
verify_abort() {
  local reason="$1" stage="$2"
  verify_check 'final safety gate' FAIL "$reason"
  verify_write_report "$stage" FAILED || :
  verify_emit_summary "$stage" FAILED >&2
  printf 'CRT installer stopped: %s. No successful installation handoff.\n' "$reason" >&2
  if declare -F log_event >/dev/null 2>&1; then
    log_event ERROR 24_finish verification_blocked stage "$stage" reason "$reason" || :
  fi
  return 1
}
